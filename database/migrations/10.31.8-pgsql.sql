CREATE TABLE IF NOT EXISTS cms_site_admin_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 site_id BIGINT NOT NULL REFERENCES cms_sites(id) ON DELETE RESTRICT,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 active_session_id BIGINT NOT NULL UNIQUE REFERENCES active_sessions(id) ON DELETE CASCADE,
 session_hash CHAR(64) NOT NULL UNIQUE,
 bound_host VARCHAR(253) NOT NULL,
 auth_provider VARCHAR(20) NOT NULL CHECK(auth_provider IN('password','vazin_id')),
 session_version INTEGER NOT NULL CHECK(session_version>0),
 authenticated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMP NOT NULL,
 revoked_at TIMESTAMP,
 FOREIGN KEY(site_id,user_id) REFERENCES cms_site_memberships(site_id,user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_cms_site_admin_session_owner
 ON cms_site_admin_sessions(site_id,user_id,revoked_at,expires_at);

-- Permanent site-session revocation on membership/domain changes.
-- This complements but does not replace dynamic membership checks.
CREATE OR REPLACE FUNCTION cms_site_admin_revoke_membership() RETURNS trigger
LANGUAGE plpgsql AS $phase11_mem$
BEGIN
  IF TG_OP='DELETE' THEN
    UPDATE cms_site_admin_sessions SET revoked_at=CURRENT_TIMESTAMP
    WHERE site_id=OLD.site_id AND user_id=OLD.user_id AND revoked_at IS NULL;
    RETURN OLD;
  END IF;
  IF OLD.site_role IS DISTINCT FROM NEW.site_role THEN
    UPDATE cms_site_admin_sessions SET revoked_at=CURRENT_TIMESTAMP
    WHERE site_id=OLD.site_id AND user_id=OLD.user_id AND revoked_at IS NULL;
  END IF;
  RETURN NEW;
END $phase11_mem$;
CREATE TRIGGER trg_cms_site_admin_member_delete AFTER DELETE
ON cms_site_memberships FOR EACH ROW EXECUTE FUNCTION cms_site_admin_revoke_membership();
CREATE TRIGGER trg_cms_site_admin_member_role AFTER UPDATE OF site_role
ON cms_site_memberships FOR EACH ROW EXECUTE FUNCTION cms_site_admin_revoke_membership();

CREATE OR REPLACE FUNCTION cms_site_admin_revoke_domain() RETURNS trigger
LANGUAGE plpgsql AS $phase11_domain$
BEGIN
  IF TG_OP='DELETE' THEN
    UPDATE cms_site_admin_sessions SET revoked_at=CURRENT_TIMESTAMP
    WHERE site_id=OLD.site_id AND bound_host=lower(OLD.domain) AND revoked_at IS NULL;
    RETURN OLD;
  END IF;
  IF lower(OLD.domain) IS DISTINCT FROM lower(NEW.domain)
    OR (OLD.verified_at IS NOT NULL AND NEW.verified_at IS NULL) THEN
    UPDATE cms_site_admin_sessions SET revoked_at=CURRENT_TIMESTAMP
    WHERE site_id=OLD.site_id AND bound_host=lower(OLD.domain) AND revoked_at IS NULL;
  END IF;
  RETURN NEW;
END $phase11_domain$;
CREATE TRIGGER trg_cms_site_admin_domain_delete AFTER DELETE
ON cms_site_domains FOR EACH ROW EXECUTE FUNCTION cms_site_admin_revoke_domain();
CREATE TRIGGER trg_cms_site_admin_domain_change AFTER UPDATE OF domain,verified_at
ON cms_site_domains FOR EACH ROW EXECUTE FUNCTION cms_site_admin_revoke_domain();
